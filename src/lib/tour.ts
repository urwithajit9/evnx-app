/**
 * The command tour — driven by the CLI's own clap tree.
 *
 * ─── ⚠️ Why there is no list of commands in this file ────────────────────────
 *
 * There have been five documentation errors of one shape in this project, and
 * every one was found by a hand sweep, which does not repeat:
 *
 *   • `evnx vault rekey` documented before it existed
 *   • `commands/auth` missing four subcommands for a whole release
 *   • `cloud delete-version` shipping with no row in its own table
 *   • `EVNX_COMMANDS` in evnx-web omitting `spec` entirely
 *   • PyPI shipping five releases with no cloud commands at all
 *
 * All of them are "a second list of what the CLI does, maintained by hand".
 * `command-surface.json` is generated by `evnx surface`, which walks the same
 * clap tree that parses the arguments — so a new command appears in this tour
 * by construction, and a removed one cannot linger.
 *
 * ⚠️ **NOTES ARE AN OVERLAY, NEVER THE SPINE.** The prose below is keyed by
 * command path. A command with no note still appears, described by its own
 * `--help` text. A note for a command that no longer exists is reported by
 * {@link tourDrift} rather than silently rendering nothing — because an orphaned
 * note is the same failure in miniature, and it is the one that would creep back.
 */

import surface from "@/data/command-surface.json";

/** Bumped by `evnx surface` when the payload shape changes. */
const SUPPORTED_SCHEMA = 1;

export type SurfaceArg = {
  id: string;
  long: string | null;
  short: string | null;
  help: string | null;
  value_name: string | null;
  required: boolean;
  takes_value: boolean;
  positional: boolean;
  multiple: boolean;
  hidden: boolean;
};

export type SurfaceCommand = {
  path: string[];
  name: string;
  about: string | null;
  visible_aliases: string[];
  aliases: string[];
  hidden: boolean;
  docs_url: string | null;
  args: SurfaceArg[];
};

export type Surface = {
  schema: number;
  evnx_version: string;
  features: string[];
  commands: SurfaceCommand[];
};

const data = surface as Surface;

/** The CLI version this tour describes. Shown, because it will go stale. */
export const EVNX_VERSION = data.evnx_version;

/**
 * ⚠️ Top-level commands that need an account.
 *
 * The one hand-kept list here, and it is four strings rather than eighty — the
 * difference that matters. `clap` does not know which Cargo feature gated a
 * command (an absent command is simply absent), so this cannot be derived from
 * the surface.
 *
 * It degrades safely: a fifth cloud command that nobody adds here appears under
 * "On your machine" — visible and mis-grouped, never missing. {@link tourDrift}
 * reports any entry that no longer exists.
 */
const CLOUD_ROOTS = ["auth", "vault", "org", "cloud"] as const;

/**
 * An order for the first few, so the tour opens on something useful rather than
 * alphabetically on `add`.
 *
 * ⚠️ A ranking, not a list. Anything unranked sorts after, in surface order, so
 * forgetting to rank a new command costs it a position and never its place.
 */
const FIRST: readonly string[] = ["init", "scan", "validate", "diff", "convert"];

export type TourGroup = {
  id: "local" | "cloud";
  title: string;
  blurb: string;
  commands: TourCommand[];
};

export type TourCommand = SurfaceCommand & {
  /** Hand-written, optional. See the note at the top of this file. */
  note?: string;
  /** A copy-pasteable line. Optional, same rule. */
  example?: string;
  subcommands: SurfaceCommand[];
};

