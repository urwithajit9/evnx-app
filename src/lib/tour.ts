function isCloud(root: string): boolean {
  return (CLOUD_ROOTS as readonly string[]).includes(root);
}

/** Top-level, visible commands, ranked. */
function roots(): SurfaceCommand[] {
  const top = data.commands.filter((c) => c.path.length === 1 && !c.hidden);
  return top.sort((a, b) => {
    const ia = FIRST.indexOf(a.name);
    const ib = FIRST.indexOf(b.name);
    if (ia !== -1 || ib !== -1) {
      return (ia === -1 ? Number.MAX_SAFE_INTEGER : ia) - (ib === -1 ? Number.MAX_SAFE_INTEGER : ib);
    }
    return 0; // surface order, which is clap's declaration order
  });
}

export function tourGroups(): TourGroup[] {
  const build = (ids: SurfaceCommand[]): TourCommand[] =>
    ids.map((c) => ({
      ...c,
      note: NOTES[c.name]?.note,
      example: NOTES[c.name]?.example,
      // ⚠️ Every descendant, not just depth 2. The first version filtered on
      // `path.length === 2` and silently dropped eleven commands —
      // `auth token create`, `auth totp enable`, `auth sessions revoke` and the
      // rest. A tour that is missing commands is the exact failure the generated
      // spine exists to prevent, reintroduced by the consumer.
      // `unreachableCommands()` is the check that now catches it.
      subcommands: data.commands.filter(
        (s) => s.path.length > 1 && s.path[0] === c.name && !s.hidden,
      ),
    }));

  const all = roots();
  return [
    {
      id: "local",
      title: "On your machine",
      blurb:
        "No account, no network. These work on a plane, in an air-gapped build, and in a CI job with egress rules.",
      commands: build(all.filter((c) => !isCloud(c.name))),
    },
    {
      id: "cloud",
      title: "With an evnx account",
      blurb:
        "Encrypted sync, team sharing and plans. Everything is encrypted on your machine before it leaves — the server holds only ciphertext it cannot read.",
      commands: build(all.filter((c) => isCloud(c.name))),
    },
  ];
}

/**
 * Everything the tour can tell is wrong about itself.
 *
 * ⚠️ This is the point of the whole design. The generated spine cannot drift,
 * but the overlay can — so the overlay is checked against the spine and the
 * result is **rendered**, not logged. A warning nobody sees is not a check.
 */
export function tourDrift(): string[] {
  const problems: string[] = [];

  if (data.schema !== SUPPORTED_SCHEMA) {
    problems.push(
      `command-surface.json is schema ${data.schema}; this tour understands ${SUPPORTED_SCHEMA}. Regenerate it and update src/lib/tour.ts together.`,
    );
  }

  if (!data.features.includes("cloud")) {
    problems.push(
      "command-surface.json came from a binary built without the `cloud` feature, so every cloud command is missing from this tour.",
    );
  }

  // ⚠️ The check that matters: does the tour actually reach every command?
  //
  // A generated list is only half the guarantee — the consumer can still drop
  // part of it. This one did, on the first attempt, by assuming subcommands
  // were one level deep.
  const unreachable = unreachableCommands();
  if (unreachable.length > 0) {
    problems.push(
      `${unreachable.length} command${unreachable.length === 1 ? " is" : "s are"} in the CLI but not shown anywhere in this tour: ${unreachable
        .slice(0, 6)
        .join(", ")}${unreachable.length > 6 ? ", …" : ""}`,
    );
  }

  const names = new Set(data.commands.filter((c) => c.path.length === 1).map((c) => c.name));

  for (const key of Object.keys(NOTES)) {
    if (!names.has(key)) {
      problems.push(`a tour note describes \`evnx ${key}\`, which is no longer a command.`);
    }
  }
  for (const root of CLOUD_ROOTS) {
    if (!names.has(root)) {
      problems.push(`\`${root}\` is listed as a cloud command but is not in the surface.`);
    }
  }
  for (const r of FIRST) {
    if (!names.has(r)) {
      problems.push(`\`${r}\` is ranked first in the tour but is not a command.`);
    }
  }

  return problems;
}

/**
 * Visible commands in the surface that the tour does not render.
 *
 * ⚠️ Compares against what {@link tourGroups} actually builds, not against what
 * it is supposed to build — a check written from the same assumption as the code
 * it checks would have passed while eleven commands were missing.
 */
export function unreachableCommands(): string[] {
  const shown = new Set<string>();
  for (const g of tourGroups()) {
    for (const c of g.commands) {
      shown.add(c.path.join(" "));
      for (const s of c.subcommands) shown.add(s.path.join(" "));
    }
  }
  return data.commands
    .filter((c) => !c.hidden)
    .map((c) => c.path.join(" "))
    .filter((p) => !shown.has(p));
}

/** `evnx vault share` — for display and copying. */
export function invocation(c: { path: string[] }): string {
  return `evnx ${c.path.join(" ")}`;
}

/** `--severity <LEVEL>`, or `--verbose` for a flag. */
export function flagLabel(a: SurfaceArg): string {
  if (a.positional) return `<${a.value_name ?? a.id.toUpperCase()}>`;
  const name = a.long ? `--${a.long}` : a.short ? `-${a.short}` : a.id;
  return a.takes_value ? `${name} <${a.value_name ?? "VALUE"}>` : name;
}
